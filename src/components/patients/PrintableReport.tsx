import React, { forwardRef } from "react";

export const PrintableReport = forwardRef<HTMLDivElement, { patient: any, clinicName?: string, language?: string }>((props, ref) => {
  const { patient, clinicName = "Prime Physio", language = "ar" } = props;
  const isRtl = language === "ar";
  
  const today = new Date().toLocaleDateString(isRtl ? 'ar-EG' : 'en-US', {
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  return (
    <div ref={ref} className="bg-white text-black p-8 max-w-[210mm] min-h-[297mm] mx-auto print:block hidden" dir={isRtl ? "rtl" : "ltr"}>
      {/* Header */}
      <div className="flex justify-between items-center border-b-2 border-slate-800 pb-4 mb-6">
        <div>
          <h1 className="text-2xl font-bold text-slate-800">{clinicName}</h1>
          <p className="text-sm text-slate-500">{isRtl ? "قسم العلاج الطبيعي والتأهيل" : "Physiotherapy & Rehabilitation Department"}</p>
        </div>
        <div className="text-right">
          <h2 className="text-xl font-bold text-slate-800 uppercase tracking-widest">{isRtl ? "تقرير طبي" : "MEDICAL REPORT"}</h2>
          <p className="text-sm text-slate-500">{isRtl ? "التاريخ:" : "Date:"} {today}</p>
        </div>
      </div>

      {/* Patient Demographics */}
      <div className="mb-6 bg-slate-50 p-4 rounded-lg border border-slate-200">
        <h3 className="text-sm font-bold text-slate-800 uppercase mb-3 border-b pb-1">{isRtl ? "بيانات المريض" : "Patient Information"}</h3>
        <div className="grid grid-cols-2 gap-4 text-sm">
          <div><span className="font-semibold text-slate-600">{isRtl ? "الاسم:" : "Name:"}</span> {isRtl ? patient.nameAr : patient.nameEn || patient.nameAr}</div>
          <div><span className="font-semibold text-slate-600">{isRtl ? "العمر:" : "Age:"}</span> {patient.age} {isRtl ? "سنة" : "Years"}</div>
          <div><span className="font-semibold text-slate-600">{isRtl ? "الجنس:" : "Gender:"}</span> {patient.gender}</div>
          <div><span className="font-semibold text-slate-600">{isRtl ? "رقم الهاتف:" : "Phone:"}</span> {patient.phone}</div>
          <div className="col-span-2"><span className="font-semibold text-slate-600">{isRtl ? "رقم الملف:" : "Patient ID:"}</span> {patient.id}</div>
        </div>
      </div>

      {/* Clinical Summary */}
      <div className="mb-6">
        <h3 className="text-lg font-bold text-slate-800 border-b-2 border-slate-100 pb-1 mb-3">{isRtl ? "الملخص السريري" : "Clinical Summary"}</h3>
        <div className="space-y-4 text-sm">
          <div>
            <p className="font-bold text-slate-700">{isRtl ? "التشخيص الأساسي (Diagnosis):" : "Diagnosis:"}</p>
            <p className="text-slate-600 mt-1">{patient.diagnosis || (isRtl ? "غير مسجل" : "Not recorded")}</p>
          </div>
          <div>
            <p className="font-bold text-slate-700">{isRtl ? "الشكوى الرئيسية (Chief Complaint):" : "Chief Complaint:"}</p>
            <p className="text-slate-600 mt-1">{patient.chiefComplaint || (isRtl ? "غير مسجل" : "Not recorded")}</p>
          </div>
          <div>
            <p className="font-bold text-slate-700">{isRtl ? "التاريخ المرضي (Medical History):" : "Medical History:"}</p>
            <p className="text-slate-600 mt-1">{patient.medicalHistory || (isRtl ? "غير مسجل" : "Not recorded")}</p>
          </div>
        </div>
      </div>

      {/* Current Protocol (If available) */}
      {patient.active_protocol && (
        <div className="mb-6">
          <h3 className="text-lg font-bold text-slate-800 border-b-2 border-slate-100 pb-1 mb-3">{isRtl ? "خطة التأهيل الحالية" : "Current Rehab Protocol"}</h3>
          <div className="bg-teal-50/50 p-4 rounded-lg border border-teal-100 text-sm">
            <p className="font-bold text-teal-800 mb-2">
              {isRtl ? "معرف البروتوكول:" : "Protocol ID:"} {patient.active_protocol.protocolId}
            </p>
            <p className="text-teal-700">
              {isRtl ? "المرحلة الحالية:" : "Current Phase:"} {patient.active_protocol.currentPhaseIndex !== undefined ? patient.active_protocol.currentPhaseIndex + 1 : patient.active_protocol.currentPhase}
            </p>
          </div>
        </div>
      )}

      {/* Footer */}
      <div className="mt-20 pt-8 border-t border-slate-200 flex justify-between items-end text-sm text-slate-600">
        <div>
          <p>{isRtl ? "صدر هذا التقرير من النظام الإلكتروني لعيادة" : "This report was generated by the EMR system of"}</p>
          <p className="font-bold text-slate-800">{clinicName}</p>
        </div>
        <div className="text-center">
          <p className="mb-8">{isRtl ? "توقيع الطبيب المعالج" : "Attending Therapist Signature"}</p>
          <div className="w-40 border-b border-slate-400"></div>
        </div>
      </div>
    </div>
  );
});

PrintableReport.displayName = "PrintableReport";
